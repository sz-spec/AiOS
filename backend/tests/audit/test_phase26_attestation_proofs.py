# ---------------------------------------------------------------------------
# TC3 — single-byte tamper of audit path OR leaf -> verification fails hard
# ---------------------------------------------------------------------------


def test_tc3_tampered_audit_path_byte_fails(ledger):
    for i in range(5):
        rec = ledger.record(
            event_type="regional_policy_enforcement",
            schema_hash="d" * 64,
            metadata={"n": i},
        )
        if i == 2:
            target = rec
    proof = ledger.generate_proof(target["event_id"])
    assert verify_proof(proof) is True  # baseline: untampered passes

    # Flip one byte of the first audit-path node.
    tampered = copy.deepcopy(proof)
    h0 = bytearray(bytes.fromhex(tampered["audit_path"][0]))
    h0[0] ^= 0x01
    tampered["audit_path"][0] = h0.hex()
    assert verify_proof(tampered) is False


def test_tc3_tampered_leaf_byte_fails(ledger):
    for i in range(5):
        rec = ledger.record(
            event_type="eu_local_enforcement", schema_hash="e" * 64, metadata={"n": i}
        )
        if i == 1:
            target = rec
    proof = ledger.generate_proof(target["event_id"])
    assert verify_proof(proof) is True

    # Flip one byte of the leaf payload.
    tampered = copy.deepcopy(proof)
    raw = bytearray(base64.b64decode(tampered["leaf_payload_b64"]))
    raw[0] ^= 0x01
    tampered["leaf_payload_b64"] = base64.b64encode(bytes(raw)).decode("ascii")
    assert verify_proof(tampered) is False


def test_tc3_forged_root_fails_sth(ledger):
    # A structurally-valid inclusion path against a DIFFERENT (forged) root must
    # fail the STH signature check even if inclusion alone might be coerced.
    ledger.record(event_type="x", schema_hash="f" * 64, metadata={})
    target = ledger.record(event_type="y", schema_hash="0" * 64, metadata={})
    proof = ledger.generate_proof(target["event_id"])
    tampered = copy.deepcopy(proof)
    root = bytearray(bytes.fromhex(tampered["root_hash"]))
    root[0] ^= 0x01
    tampered["root_hash"] = root.hex()
    assert verify_proof(tampered) is False


