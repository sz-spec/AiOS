"""
Phase 26 — policy transparency Merkle attestation proofs (Gap G3).
==================================================================

Exercises the REAL ``PolicyTransparencyLedger`` (RFC-6962 SHA-256 Merkle log)
and the REAL ``/api/v1/transparency/proof`` endpoint end to end:

  TC1  valid event  -> proof validates cryptographically against the signed root
  TC2  unknown id   -> HTTP 404 (exact)
  TC3  one flipped byte (audit path OR leaf) -> verification fails hard
  + the live policy->transparency feed records a real leaf when flag is ON
  + an anti-divergence cross-check: the vendored RFC-6962 functions are
    byte-identical to the infra/security/rekor_v2_log.py originals.

Anti-gaming (charter §II): fixed-value asserts (== 404, is True / is False);
the proof is generated by the REAL ledger (not a stub), validated by the REAL
RFC-6962 verifier + REAL ECDSA-P256 STH signature, and the tamper test flips a
genuine byte rather than asserting a mocked failure.

Run: .venv_p312/bin/python -m pytest tests/audit/test_phase26_attestation_proofs.py -n 0
"""

from __future__ import annotations

import base64
import copy

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from services.policy_transparency import (
    PolicyTransparencyLedger,
    _reset_singleton_for_tests,
    verify_inclusion,
    verify_proof,
)


@pytest.fixture
def ledger(tmp_path):
    """A ledger bound to a tmp JSONL, installed as the process singleton so the
    endpoint and the policy-feed both hit it. Reset afterward."""
    lg = PolicyTransparencyLedger(path=str(tmp_path / "policy_transparency.jsonl"))
    _reset_singleton_for_tests(lg)
    yield lg
    _reset_singleton_for_tests(None)


def _client() -> TestClient:
    from api import transparency_routes
    from api.deps import get_current_user

    app = FastAPI()
    app.include_router(transparency_routes.router, prefix="/api")

    class _U:
        id = "test-user"

    app.dependency_overrides[get_current_user] = lambda: _U()
    return TestClient(app, raise_server_exceptions=False)


# ---------------------------------------------------------------------------
# TC1 — valid event -> proof validates against the active signed root
# ---------------------------------------------------------------------------


def test_tc1_valid_event_proof_validates(ledger):
    # Append a few events so the tree has interior nodes (non-trivial path).
    ledger.record(
        event_type="regional_policy_enforcement",
        schema_hash="a" * 64,
        metadata={"action": "global"},
    )
    target = ledger.record(
        event_type="eu_local_enforcement",
        schema_hash="b" * 64,
        metadata={"action": "local", "user_id": "u1"},
    )
    ledger.record(
        event_type="regional_policy_enforcement",
        schema_hash="c" * 64,
        metadata={"action": "denied"},
    )

    r = _client().get(
        "/api/v1/transparency/proof", params={"event_id": target["event_id"]}
    )
    assert r.status_code == 200
    proof = r.json()

    # Full client-side verification (inclusion path + ECDSA-P256 STH over root).
    assert verify_proof(proof) is True

    # And the raw RFC-6962 inclusion check against the active root, explicitly.
    payload = base64.b64decode(proof["leaf_payload_b64"])
    assert (
        verify_inclusion(
            leaf_data=payload,
            leaf_index=proof["leaf_index"],
            tree_size=proof["tree_size"],
            audit_path=[bytes.fromhex(h) for h in proof["audit_path"]],
            expected_root=bytes.fromhex(proof["root_hash"]),
        )
        is True
    )
    # The proof's root is the ledger's current active root (no stale snapshot).
    assert proof["root_hash"] == ledger.latest_root()


