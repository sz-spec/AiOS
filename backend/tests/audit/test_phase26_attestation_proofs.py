# Live policy -> transparency feed (flag-gated) records a real leaf
# ---------------------------------------------------------------------------


def test_policy_feed_records_when_flag_on(ledger, monkeypatch):
    monkeypatch.setenv("VOS3_POLICY_TRANSPARENCY_ENABLED", "1")
    from services import regional_policy as rp

    before = ledger.tree_size()
    decision = rp.classify_zone("DE", consent_to_global=False)
    # enforce_routing logs + feeds; DE w/o consent + no local lane -> denial,
    # but the AUDIT FEED fires on every branch (including denial).
    with pytest.raises(rp.ComplianceDenied):
        rp.enforce_routing(decision, user_id_for_log="clerk_abc")
    assert ledger.tree_size() == before + 1

    # The freshly-fed event is provable end to end.
    last_id = ledger._records[-1]["event_id"]  # noqa: SLF001 (test introspection)
    proof = ledger.generate_proof(last_id)
    assert verify_proof(proof) is True


def test_policy_feed_noop_when_flag_off(ledger, monkeypatch):
    monkeypatch.delenv("VOS3_POLICY_TRANSPARENCY_ENABLED", raising=False)
    from services import regional_policy as rp

    before = ledger.tree_size()
    decision = rp.classify_zone("US", consent_to_global=False)
    rp.enforce_routing(decision, user_id_for_log="clerk_us")  # "global", no raise
    assert ledger.tree_size() == before  # flag OFF -> no leaf written


# ---------------------------------------------------------------------------
# Anti-divergence: vendored RFC-6962 funcs == infra/security originals
# ---------------------------------------------------------------------------


def test_vendored_merkle_matches_infra_original():
    import os
    import sys

    repo_root = os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "..", "..")
    )
    if repo_root not in sys.path:
        sys.path.insert(0, repo_root)
    try:
        from infra.security import rekor_v2_log as orig
    except Exception:  # pragma: no cover - infra not importable in this env
        pytest.skip("infra.security.rekor_v2_log not importable in this environment")

    from services import policy_transparency as vend

    leaves_data = [b"", b"a"] + [b"policy-event-%d" % i for i in range(13)]
    leaves = [vend.leaf_hash(d) for d in leaves_data]
    orig_leaves = [orig.leaf_hash(d) for d in leaves_data]
    assert leaves == orig_leaves

    assert vend.compute_root(leaves) == orig.compute_root(orig_leaves)
    for idx in range(len(leaves)):
        assert vend.compute_inclusion_path(leaves, idx) == orig.compute_inclusion_path(
            orig_leaves, idx
        )
        path = vend.compute_inclusion_path(leaves, idx)
        assert (
            vend.verify_inclusion(
                leaf_data=leaves_data[idx],
                leaf_index=idx,
                tree_size=len(leaves),
                audit_path=path,
                expected_root=vend.compute_root(leaves),
            )
            is True
        )
