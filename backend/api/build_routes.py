"""
Build Progress Routes
=====================
SSE endpoint for streaming build progress events to the frontend.
"""

import asyncio
import json
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse

from api.deps import get_current_user, AuthenticatedUser
from services.project_service import get_project_service

router = APIRouter(prefix="/api/v1/build", tags=["Build"])


# =============================================================================
# Build Pipeline Stages
# =============================================================================

BUILD_STAGES = [
    {"id": "architect", "label": "Architect", "duration": 3.0},
    {"id": "frontend", "label": "Frontend", "duration": 5.0},
    {"id": "backend", "label": "Backend", "duration": 4.0},
    {"id": "testing", "label": "Testing", "duration": 2.0},
    {"id": "review", "label": "Review", "duration": 2.0},
    {"id": "done", "label": "Done", "duration": 0.5},
]


def sse_event(data: dict) -> str:
    """Format a dict as an SSE event."""
    return f"data: {json.dumps(data)}\n\n"


# =============================================================================
# SSE Endpoint
# =============================================================================


@router.get("/{project_id}/stream")
async def stream_build_progress(
    project_id: str, user: AuthenticatedUser = Depends(get_current_user)
):
    """
    Stream build progress events via SSE.

    Events:
    - node_start: A pipeline node has started
    - node_complete: A pipeline node has finished
    - node_error: A pipeline node has failed
    - build_complete: The entire build is done

    In production, this will be driven by real multi-agent events.
    For now, it simulates progress with timed stages.
    """
    service = get_project_service()
    project = service.get(project_id)

    async def event_generator():
        # If project doesn't exist, send error and close
        if not project:
            yield sse_event(
                {
                    "type": "node_error",
                    "node_id": "architect",
                    "message": "Project not found",
                }
            )
            return

        # Ownership check — prevent cross-tenant IDOR
        owner = getattr(project, "user_id", None) or getattr(project, "owner_id", None)
        if owner is not None and owner != user.id:
            yield sse_event(
                {
                    "type": "node_error",
                    "node_id": "architect",
                    "message": "Access denied",
                }
            )
            return

        # Simulate pipeline execution
        for stage in BUILD_STAGES:
            # Node start
            yield sse_event(
                {
                    "type": "node_start",
                    "node_id": stage["id"],
                    "label": stage["label"],
                }
            )

            # Simulate work
            await asyncio.sleep(stage["duration"])

            # Node complete
            yield sse_event(
                {
                    "type": "node_complete",
                    "node_id": stage["id"],
                    "label": stage["label"],
                }
            )

        # Generate sample files for the project
        sample_files = _generate_sample_files(project.category, project.description)
        service.update_files(project_id, sample_files)
        service.update(project_id, status="ready")

        # Build complete
        yield sse_event(
            {
                "type": "build_complete",
                "project_id": project_id,
                "files_count": len(sample_files),
            }
        )

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # Disable nginx buffering
        },
    )


