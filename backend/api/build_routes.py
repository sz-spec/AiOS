@router.get("/{project_id}/download")
async def download_project_zip(
    project_id: str, user: AuthenticatedUser = Depends(get_current_user)
):
    """Download project as ZIP with VOS3 Native SDK included."""
    import io
    import zipfile as zf
    from fastapi.responses import StreamingResponse as ZipStreamingResponse

    service = get_project_service()
    project = service.get(project_id)
    if not project:
        from fastapi import HTTPException

        raise HTTPException(status_code=404, detail="Project not found")

    # Ownership check — prevent cross-tenant IDOR
    from fastapi import HTTPException as _HTTPException

    owner = getattr(project, "user_id", None) or getattr(project, "owner_id", None)
    if owner is not None and owner != user.id:
        raise _HTTPException(status_code=403, detail="Access denied")

    buf = io.BytesIO()
    with zf.ZipFile(buf, "w", zf.ZIP_DEFLATED) as z:
        # Project files
        files = getattr(project, "files", None) or {}
        for path, content in files.items():
            z.writestr(path, content)
        # Native SDK
        z.writestr("vos3/VOS3_SDK.h", VOS3_SDK_H)
        z.writestr("vos3/Makefile.native", MAKEFILE_NATIVE)

    buf.seek(0)
    return ZipStreamingResponse(
        buf,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{project_id}.zip"'},
    )


